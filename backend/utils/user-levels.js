function getUserLevel(coinsGifted) {
  let level = 0;
  for (let i = 1; i <= 100; i++) {
    if (coinsGifted >= THRESHOLDS[i]) level = i;
    else break;
  }
  return level;
}

async function getUserLevelFromDb(db, userId) {
  try {
    const r = await db.query(
      `SELECT COALESCE(SUM(coins * quantity), 0)::int AS coins_gifted
       FROM room_gift_events WHERE sender_id = $1`,
      [userId]
    );
    const coinsGifted = parseInt(r.rows[0]?.coins_gifted ?? 0, 10);
    return getUserLevel(coinsGifted);
  } catch {
    return 0;
  }
}

